def cuisine_of(name, tags):
    for t in tags:
        if t in TAG_CUIS:
            return TAG_CUIS[t]
    for c, rx in CUIS_C:
        m = rx.search(name)
        if m and (len(m.group(0)) > 1 or len(name) <= 6):
            return c
    return '中餐'


def region_of(name, tags):
    s = name + ' ' + ' '.join(tags)
    for c, rx in REGION_C:
        if rx.search(s):
            return c
    return ''


def kinds_of(name, tags):
    s = ' '.join(tags)
    out = [c for c, rx in KINDS_C if rx.search(s)]
    for c, rx in NAME_KIND:
        if c not in out and rx.search(name):
            out.append(c)
    return out


def score(steps, ings, desc):
    sc = 0.0
    ns, ni = len(steps), len(ings)
    sc += 3 if 4 <= ns <= 18 else (1 if 3 <= ns <= 25 else -3)
    sc += 2 if 3 <= ni <= 20 else (0 if 2 <= ni <= 30 else -3)
    L = [len(s) for s in steps] or [0]
    avg = sum(L) / len(L)
    sc += 2 if 12 <= avg <= 120 else (0 if 6 <= avg <= 200 else -2)
    if desc:
        sc += 1 if 10 <= len(desc) <= 300 else 0
    if any(len(s) < 4 for s in steps):
        sc -= 1
    if BAD.search(' '.join(steps) + desc):
        sc -= 4
    if sum(1 for s in steps if re.search(r'\d', s)) >= ns * 0.5:
        sc += 1
    if sum(1 for i in ings if re.search(r'\d', i)) < ni * 0.3:
        sc -= 0.5
    return sc


def norm(s):
    return STRIP.sub('', s)


